/* Generated-image production prep: crop alpha bounds, nearest-neighbour pack, never repaint art.
   npm install --prefix /tmp/pixel-tools pngjs
   NODE_PATH=/tmp/pixel-tools/node_modules node scripts/sprites/pixel-v2.cjs */
const fs=require('fs'),path=require('path'),{PNG}=require('pngjs');
const root=path.resolve(__dirname,'../../web/pixel/v2');
const cast={claude:'Claude · 팀장',gpt:'GPT · 디자이너',gemini:'Gemini · 업무 지원',design:'디자인팀장',head:'본부장',finance:'경리팀장',intern:'인턴',courier:'택배 기사',visitor:'방문객'};
const poses=['stand.front','stand.side','stand.back','portrait','walk.front.0','walk.front.1','walk.back.0','walk.back.1','walk.side.0','walk.side.1','sit.front','sit.side','sit.back','tea.front','tea.side','present.front'];
const furniture=['desk','leaderDesk','meetingTable','sofa','coffeeCounter','bookcase','plant','reception','display','coffeeTable','chair','lamp'];
function bounds(im,col,row,cols,rows){
 const x0=Math.round(col*im.width/cols),y0=Math.round(row*im.height/rows),x1=Math.round((col+1)*im.width/cols),y1=Math.round((row+1)*im.height/rows);
 let left=x1,top=y1,right=x0,bottom=y0,count=0;
 for(let y=y0;y<y1;y++)for(let x=x0;x<x1;x++)if(im.data[(y*im.width+x)*4+3]>96){left=Math.min(left,x);top=Math.min(top,y);right=Math.max(right,x);bottom=Math.max(bottom,y);count++;}
 if(count<100)throw Error('Empty sprite cell');
 return {x:left,y:top,w:right-left+1,h:bottom-top+1};
}
function copyNearest(src,b,dst,dx,dy,w,h){for(let y=0;y<h;y++)for(let x=0;x<w;x++){
 const si=((b.y+Math.min(b.h-1,Math.floor((y+.5)*b.h/h)))*src.width+b.x+Math.min(b.w-1,Math.floor((x+.5)*b.w/w)))*4,di=((dy+y)*dst.width+dx+x)*4;
 src.data.copy(dst.data,di,si,si+4);
}}
function save(rel,im){const file=path.join(root,rel);fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,PNG.sync.write(im));return 'pixel/v2/'+rel;}
const out={version:2,characters:{},furniture:{}};
for(const [id,label]of Object.entries(cast)){
 const im=PNG.sync.read(fs.readFileSync(path.join(root,'sources',id+'.png'))),cells=poses.map((_,i)=>bounds(im,i%4,Math.floor(i/4),4,4));
 if(im.data[3]>8)throw Error(id+' must have transparent alpha');
 const atlas=new PNG({width:256,height:256}),frames={};
 cells.forEach((b,i)=>{
  // Generated rows have small scale differences. Normalize animation heights and foot anchors.
  const target=[10,11,12].includes(i)?40:48;
  const s=i===3?48/Math.max(b.w,b.h):target/b.h,w=Math.round(b.w*s),h=Math.round(b.h*s),x=i%4*64+Math.floor((64-w)/2),y=Math.floor(i/4)*64+60-h;
  if(w>60||h>60)throw Error(id+' frame exceeds cell');
  copyNearest(im,b,atlas,x,y,w,h);frames[poses[i]]={x,y,w,h};
 });
 const portrait=new PNG({width:48,height:48}),b=cells[3],s=46/Math.max(b.w,b.h),w=Math.round(b.w*s),h=Math.round(b.h*s);
 copyNearest(im,b,portrait,Math.floor((48-w)/2),48-h,w,h);
 out.characters[id]={label,src:save('characters/'+id+'.png',atlas),portrait:save('portraits/'+id+'.png',portrait),frames};
}
const im=PNG.sync.read(fs.readFileSync(path.join(root,'sources/furniture.png')));
furniture.forEach((id,i)=>{const b=bounds(im,i%4,Math.floor(i/4),4,3),scale=96/Math.max(b.w,b.h),w=Math.round(b.w*scale),h=Math.round(b.h*scale),cv=new PNG({width:w,height:h});copyNearest(im,b,cv,0,0,w,h);out.furniture[id]={src:save('furniture/'+id+'.png',cv),w,h};});
fs.writeFileSync(path.join(root,'manifest.json'),JSON.stringify(out,null,2)+'\n');
fs.writeFileSync(path.join(root,'assets.js'),'/* Generated by scripts/sprites/pixel-v2.cjs. */\nwindow.PIXEL_ASSETS_V2='+JSON.stringify(out)+';\n');
console.log('9 character atlases / 9 portraits / 12 furniture assets packed.');
