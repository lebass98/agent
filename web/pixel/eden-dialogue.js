  const ANIMAL_KO = { fox: "여우", panda: "판다", otter: "수달", penguin: "어린이", elephant: "코끼리", duck: "오리", peacock: "공작", rabbit: "토끼", bear: "곰",
    cat: "고양이", dog: "강아지", lion: "사자", tiger: "호랑이", koala: "코알라", monkey: "원숭이", giraffe: "기린", meerkat: "미어캣", owl: "부엉이", raccoon: "너구리", hamster: "햄스터" };
  /** 이든이의 말 걸기·대답·끼어들기. 말풍선은 tag 의 .bubble 에 띄운다 */
  function chickEden(chick, tag, talk, me, parent) {
    const bubble = tag.querySelector(".bubble"), pick = a => a[Math.floor(Math.random() * a.length)];
    const SP = () => Math.max(1, typeof SPEED === "number" ? SPEED : 1);
    const used = [];
    const fresh = arr => { let x = pick(arr); for (let i = 0; i < 6 && used.includes(x); i++) x = pick(arr); used.push(x); if (used.length > 16) used.shift(); return x; };
    let bt = 0, lastSay = 0, z = 50;
    const sayDur = (text, minMs = 2600) => {
      const len = (text || "").length;
      return Math.min(15000, Math.max(minMs, 1800 + len * 120));
    };
    const say = (text, ms = 2600) => {
      const dur = sayDur(text, ms);
      bubble.textContent = text; bubble.style.translate = ""; bubble.classList.add("show"); tag.style.zIndex = String(9000 + (++z % 500)); lastSay = performance.now(); if (me) me.lastSay = lastSay;
      clearTimeout(bt); bt = setTimeout(() => { bubble.classList.remove("show", "covered"); bubble.style.translate = ""; }, dur / SP());
      return dur;
    };
    const later = (ms, f) => setTimeout(f, ms / SP());
    const mom = () => { try { const m = parent ? parent() : A("gpt"); return m && !m.ghost && !m.hidden && (parent ? m === parent() : m.rig?.group.userData.kind === "penguin") ? m : null; } catch { return null; } };
    const pos = () => chick.group.position;
    const gapTo = a => Math.hypot(a.group.position.x - pos().x, a.group.position.z - pos().z);
    const kindOf = a => a.rig?.group.userData.kind || a.def?.kind || a.name;
    const callName = a => {
      const who = talk.persona(a), ko = ANIMAL_KO[kindOf(a)];
      if (!ko) return talk.label(a);
      if (who === "head") return `${ko} 할아버지`;
      if (who === "duck") return `${ko} 아저씨`;
      return `${ko} ${[...a.name].reduce((s, c) => s + c.charCodeAt(0), 0) % 2 ? "이모" : "삼촌"}`;
    };
    const momSay = (m, text) => {
      if (["stand", "talk", "coffee"].includes(m.mode)) m.face(pos());
      const dur = sayDur(text, 2600);
      talk.hush(() => m.say(text, dur));
      return dur;
    };
    const ready = () => chick.group.visible && !talk.busy();
    const others = () => (talk.talkersNear ? talk.talkersNear(pos()) - (bubble.classList.contains("show") ? 1 : 0) : 0); // 이든 말고 근처에서 말하는 수
    const roomy = () => !talk.crowdAt || talk.crowdAt(pos(), mom(), 4.5) <= 1; // 엄마 빼고 둘 넘게 모여 있으면 조용히
    // 엄마에게 말 걸기 → 엄마 대답 → 가끔 이든이 한마디 더
    function toMom() {
      const m = mom(); if (!m) return false;
      const busy = talk.working(m);
      if (busy) {
        const d = say(fresh(EDEN.momBusy));
        if (Math.random() < .6) later(d + 400, () => ready() && momSay(m, fresh(EDEN.momRe.busy)));
        return true;
      }
      const [line, kind] = fresh(EDEN.mom);
      const d1 = say(line);
      talk.hold(m, d1 + 8000);
      later(d1 + 500, () => {
        if (!ready()) return;
        const reLine = fresh(EDEN.momRe[kind] || EDEN.momRe.show);
        const d2 = momSay(m, reLine);
        if (Math.random() < .7) later(d2 + 500, () => ready() && say(fresh(EDEN.after), 2600));
      });
      return true;
    }
    // 근처 팀원·조연에게 말 걸기 → 그 캐릭터 말투로 대답
    function toOthers() {
      const m = mom();
      const near = talk.everyone().filter(a => a !== m && gapTo(a) < 4.5 && !talk.engaged(a) && !a.presenting);
      if (!near.length) return false;
      const to = pick(near), who = talk.persona(to), busy = talk.working(to);
      const line = fresh(EDEN.to[who] || EDEN.to.team).replace("{n}", callName(to));
      const d1 = say(line);
      talk.hold(to, d1 + 8000);
      later(d1 + 500, () => {
        if (!ready() || !to.group || to.ghost) return;
        if (["stand", "talk", "coffee"].includes(to.mode)) to.face(pos());
        const reLine = fresh(busy ? EDEN.re.teamBusy : EDEN.re[who] || EDEN.re.team);
        const d2 = sayDur(reLine, 2600);
        talk.hush(() => to.say(reLine, d2));
        if (Math.random() < .7) later(d2 + 500, () => ready() && say(fresh(EDEN.after), 2600));
      });
      return true;
    }
    // 평소: 말이 많다 — 5~9초마다 말을 건다(엄마 6 : 다른 이 3 : 혼잣말 1)
    let next = performance.now() + 3000;
    setInterval(() => {
      const now = performance.now();
      if (now < next || !ready() || !mom()) return;
      if (others() > 0 || !roomy()) { next = now + 2500; return; } // 옆에서 누가 말하는 중이거나 붐비면 조금 뒤에
      const r = Math.random();
      if (r < .22) { const d = say(fresh(EDEN.solo), 2600); next = now + d + (3000 + Math.random() * 3000) / SP(); return; }
      if (r < .45 && toOthers()) { next = now + (9000 + Math.random() * 4000) / SP(); return; }
      toMom();
      next = now + (9000 + Math.random() * 4000) / SP();
    }, 1000);
    // 근처에서 누가 말하면 가끔 끼어든다(엄마가 가끔 타이른다)
    talk.ear((sp, text) => {
      if (!ready() || sp === undefined || performance.now() - lastSay < 3000 || talk.skipLine(text) || gapTo(sp) > 6 || Math.random() > .55 || others() > 1 || !roomy()) return;
      later(1300 + Math.random() * 700, () => {
        if (!ready() || others() > 1) return;
        const d = say(fresh(EDEN.hear[talk.topic(text)] || EDEN.hear.any), 2600);
        const m = mom();
        if (m && m !== sp && !talk.working(m) && gapTo(m) < 4 && Math.random() < .4) later(d + 400, () => ready() && momSay(m, fresh(EDEN.momRe.hush)));
      });
    });
    return { say };
  }

return chickEden;
